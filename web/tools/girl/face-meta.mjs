// tools/girl/face-meta.mjs — expression annotations (name, note, eye / mouth boxes per expression cell).
//   node tools/girl/face-meta.mjs          refs/face/face-meta.json -> src/23-girl-face3-meta.js (V3.girlFace3Meta)
//                                          (creates face-meta.json first if missing, boxes auto-detected per cell)
//   node tools/girl/face-meta.mjs --init   re-create face-meta.json from scratch (overwrites hand annotations!)
// Boxes are texture px of the face data (x right, y down): eyeR = her right eye (viewer's left), eyeL, mouth.
// They drive the blink / talk pasting (src/23-girl-face3.js) and the eye / mouth picking (src/26-girl3.js);
// the studio's 表情 panel (src/28-girl3-faces.js) edits them and POSTs /api/girl3/face-meta.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const META = path.join(ROOT, 'refs/face/face-meta.json');
const OUT = path.join(ROOT, 'src/23-girl-face3-meta.js');
const DEFAULT = {
  neutral: ['平静', '平常的样子：睁眼，ω 小嘴。默认表情。'],
  happy: ['开心', '睁眼，张嘴笑。'],
  smile: ['眯眼笑', '眼睛弯成两道弧，ω 小嘴，很满足。'],
  laugh: ['大笑', '眼睛挤成 > <，张大嘴笑。'],
  pout: ['气鼓鼓', '上眼皮压平、半眯着，嘴撇成 ^，不高兴。'],
  sleepy: ['困倦', '闭眼成一条线，嘴微微张开。'],
  talk: ['说话', '睁眼，小口张开；说话时和「闭嘴」帧来回切换。'],
  surprised: ['惊讶', '睁眼，嘴张成小圆 o。'],
  wink: ['眨眼', '画面左边的眼睛睁开，右边闭成弧，张嘴笑。'],
  half: ['半闭眼（眨眼帧）', '眨眼动画的中间帧：眼皮落到瞳孔中间。'],
  closed: ['闭眼（眨眼帧）', '眨眼动画的闭眼帧：眼睛闭成直线。'],
  mouthClosed: ['闭嘴（说话帧）', '说话动画的闭嘴帧：嘴是一条短线。'],
};

function loadData() {
  const win = { V3: {} };
  vm.runInNewContext(fs.readFileSync(path.join(ROOT, 'src/23-girl-face3-data.js'), 'utf8'), { window: win });
  return win.V3.girlFace3Data;
}
// bounding box of the pixels passing test inside rect r (texture px), padded by 1; null if none
function bbox(D, img, pal, r, test) {
  let x0 = 1e9, y0 = 1e9, x1 = -1, y1 = -1;
  for (let y = r.y; y < r.y + r.h; y++) for (let x = r.x; x < r.x + r.w; x++) {
    const c = pal[img[y * D.W + x]];
    if (test(c)) { x0 = Math.min(x0, x); y0 = Math.min(y0, y); x1 = Math.max(x1, x); y1 = Math.max(y1, y); }
  }
  if (x1 < 0) return null;
  const p = 1, X0 = Math.max(0, x0 - p), Y0 = Math.max(0, y0 - p);
  return { x: X0, y: Y0, w: Math.min(D.W, x1 + p + 1) - X0, h: Math.min(D.H, y1 + p + 1) - Y0 };
}
export function autoMeta(D) {
  const pal = D.palette.map((h) => [(h >> 16) & 255, (h >> 8) & 255, h & 255]);
  const eyeC = ([r, g, b]) => b > r + 30 || (r < 80 && g < 80 && b < 120);            // lash / iris / closed-eye lines
  const mouthC = ([r, g, b]) => (r > 140 && r - g > 40 && r - b > 25) || (r > g + 30 && r < 170 && b < r - 20);
  const R = D.regions, cells = {};
  D.cells.forEach((id, k) => {
    const img = Uint8Array.from(Buffer.from(D.img[k], 'base64'));
    // search windows (texture px): eyes left / right of the centre column and above the mouth, mouth in the middle
    const u = (x) => Math.round((x - (D.rect ? D.rect.x0 : -9)) * D.PU), v = (y) => Math.round(((D.rect ? D.rect.y1 : 17) - y) * D.PU);
    const win = (x0, x1, y0, y1) => ({ x: u(x0), y: v(y1), w: u(x1) - u(x0), h: v(y0) - v(y1) });
    const eyeR = bbox(D, img, pal, win(-9, -1.7, 2.3, 10.5), eyeC) || R.eyeR;
    const eyeL = bbox(D, img, pal, win(1.7, 9, 2.3, 10.5), eyeC) || R.eyeL;
    const mouth = bbox(D, img, pal, win(-2.6, 2.6, 0, 3.6), mouthC) || R.mouth;
    const [name, note] = DEFAULT[id] || [id, ''];
    cells[id] = { name, note, eyeR, eyeL, mouth };
  });
  return { version: 1, texture: { w: D.W, h: D.H, pxPerUnit: D.PU }, cells };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const D = loadData();
  if (!fs.existsSync(META) || process.argv.includes('--init')) {
    fs.mkdirSync(path.dirname(META), { recursive: true });
    fs.writeFileSync(META, JSON.stringify(autoMeta(D), null, 1));
    console.log('created refs/face/face-meta.json (boxes auto-detected)');
  }
  const meta = JSON.parse(fs.readFileSync(META, 'utf8'));
  for (const id of D.cells) if (!meta.cells[id]) meta.cells[id] = autoMeta(D).cells[id];   // new cells get defaults
  fs.writeFileSync(OUT, '// 23-girl-face3-meta.js — GENERATED by tools/girl/face-meta.mjs from refs/face/face-meta.json. Do not edit.\n' +
    '(function (V3) {\n  V3.girlFace3Meta = ' + JSON.stringify(meta) + ';\n})(window.V3);\n');
  console.log('wrote src/23-girl-face3-meta.js:', D.cells.map((id) => `${id}=${meta.cells[id].name}`).join(' '));
}
