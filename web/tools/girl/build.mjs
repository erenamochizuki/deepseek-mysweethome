// tools/girl/build.mjs — build a whale-girl block model and write the deliverables.
//   node tools/girl/build.mjs          v3 head (archived design, tools/girl/head.mjs)
//   node tools/girl/build.mjs --v4     v4 head (tools/girl/head4.mjs, rebuilt from the Tripo template)
//   node tools/girl/build.mjs --all    both
// Writes, per model: refs/models/<file>.glb, refs/models/<file>.manifest.json (editor manifest: blocks, control
// points, mirror pairs) and src/<asset> (glb as base64 + manifest, for the single-file studio page).
// Hand edits made in the studio editor live in refs/models/<file>.edits.json and are applied here.
// Then: node build.mjs && node tools/shoot.mjs --page studio --views "model=girl4head+front+ui=0" --out test/tmp-girl/x
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildHead } from './head.mjs';
import { buildHead4, FACE_RECT as FACE_RECT4 } from './head4.mjs';
import { toGLB, encodePNG } from './glb.mjs';
import { loadFace } from './face-sheet.mjs';
import { buildManifest } from './manifest.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const CREDIT = '角色设计：上善无形（ZipZipPipe），CC BY-NC-SA 4.0；方块模型改编：海边小屋 v3（同协议，非商用）';
const F = loadFace();
export const MODELS = {
  v3: { file: 'whale-girl-head', asset: '25-girl3-asset.js', kind: 'whale-girl-v3', rect: F.rect, build: (e) => buildHead(F, e) },
  v4: { file: 'whale-girl-head-v4', asset: '25-girl4-asset.js', kind: 'whale-girl-v4', rect: FACE_RECT4, build: (e) => buildHead4(F, e).model },
};
const argv = process.argv.slice(2);
const which = argv.includes('--all') ? ['v3', 'v4'] : argv.includes('--v4') ? ['v4'] : ['v3'];

for (const id of which) {
  const M = MODELS[id], t0 = Date.now();
  const EDITS = path.join(ROOT, `refs/models/${M.file}.edits.json`);
  let edits = null;
  if (fs.existsSync(EDITS)) {
    try { edits = JSON.parse(fs.readFileSync(EDITS, 'utf8')).edits || null; }
    catch (e) { console.error('ignoring unreadable ' + path.relative(ROOT, EDITS) + ': ' + e.message); }
  }
  const model = M.build(edits);
  const face = encodePNG(F.W, F.H, F.raster('happy'));
  const { glb, json } = toGLB(model, {
    scale: 0.02, textures: { face: { png: face } }, copyright: CREDIT,
    partPath: (p) => '头/' + p,
    extras: { kind: M.kind, stage: 'head', unitMeters: 0.02, faceTexture: { w: F.W, h: F.H, pxPerUnit: F.PX_PER_UNIT, rect: M.rect }, credit: CREDIT },
  });
  const outGlb = path.join(ROOT, `refs/models/${M.file}.glb`);
  fs.mkdirSync(path.dirname(outGlb), { recursive: true });
  fs.writeFileSync(outGlb, glb);
  const manifest = buildManifest(model, { partPath: '头/', unitMeters: 0.02 });
  fs.writeFileSync(path.join(ROOT, `refs/models/${M.file}.manifest.json`), JSON.stringify(manifest));
  const asset = `// ${M.asset} — GENERATED by tools/girl/build.mjs (refs/models/${M.file}.glb + editor manifest). Do not edit.\n` +
    '(function (V3) {\n  V3.assets = V3.assets || {};\n' +
    `  V3.assets['models/${M.file}.glb'] = '${glb.toString('base64')}';\n` +
    `  V3.assets['models/${M.file}.manifest.json'] = ${JSON.stringify(manifest)};\n})(window.V3);\n`;
  fs.writeFileSync(path.join(ROOT, 'src', M.asset), asset);
  const sum = model.summary();
  console.log(`wrote refs/models/${M.file}.glb ${(glb.length / 1024).toFixed(1)} KB, tris=${sum.tris}, blocks=${sum.blocks}, ` +
    `edited=${sum.edited}, meshes=${json.meshes.length}, bones=${model.bones.length}, ${Date.now() - t0} ms`);
  console.log('parts', JSON.stringify(sum.parts), '| mirrored blocks', manifest.elements.filter((e) => e.mirror).length);
}
