#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { photos, photoSnbt } from './photo-card.mjs';
export const CARD_FILE = fileURLToPath(new URL('../cards/P5-006.yml', import.meta.url));
export function cardText() {
  const q = s => `'${s.replaceAll("'", "''")}'`;
  const L = ['# Generated by album-carry-card.mjs. No Minecraft launch in this generator.', 'title: 相册桌拆装：64张、掉落、复制隔离、重进存档、缺失引用', 'steps:', '  - open: P5-006', '  - wait: {inWorld: true, screen: null, timeout: 180}'];
  const cmd = (s, extra = '') => L.push(`  - cmd: {command: ${q(s)}${extra ? `, ${extra}` : ''}}`);
  const use = (x, ok = true, extra = '') => L.push(`  - use: {pos: [${x}, -61, 0], face: up, consumed: ${ok}${extra}}`);
  const check = x => cmd(`data modify block ${x} -60 0 Album set from storage xiaojingyu:carry_test Album`, 'success: false');
  cmd('gamerule send_command_feedback false');
  cmd('gamerule spawn_mobs false');
  cmd('gamemode creative');
  cmd('tp @s 0.5 -60 3.5 180 20');
  cmd('fill -2 -61 -2 12 -61 2 minecraft:stone');
  cmd('setblock 0 -60 0 xiaojingyu:photo_album_table');
  cmd('data modify block 0 -60 0 Album set value []');
  const P = Object.values(photos());
  for (let i = 0; i < 64; i++) cmd(`data modify block 0 -60 0 Album append value ${photoSnbt({...P[i % P.length], name: `Snapshot ${i}`}, 1762560000000 + i)}`);
  cmd('data modify storage xiaojingyu:carry_test Album set from block 0 -60 0 Album');
  L.push('  - pick: {pos: [0, -60, 0], includeData: true, hasReference: true, hasAlbum: false, maxBytes: 1024}');
  cmd('item replace entity @s hotbar.8 from entity @s weapon.mainhand');
  cmd('setblock 0 -60 0 minecraft:air destroy');
  cmd('execute if items entity @e[type=minecraft:item,limit=1,sort=nearest] contents xiaojingyu:photo_album_table[xiaojingyu:album_reference]');
  cmd('item replace entity @s weapon.mainhand from entity @e[type=minecraft:item,limit=1,sort=nearest] contents');
  cmd('kill @e[type=minecraft:item]');
  cmd('gamemode survival');
  use(1);
  check(1);
  cmd('execute unless items entity @s weapon.mainhand *');
  cmd('gamemode creative');
  cmd('item replace entity @s weapon.mainhand from entity @s hotbar.8');
  use(3);
  check(3);
  cmd('data modify block 1 -60 0 Album[0].Name set value "edited independently"');
  check(3);
  cmd('data get block 1 -60 0 Album[0].Name', 'outputContains: edited independently');
  // Save the reference item in player inventory, stop integrated server, load same disk save.
  L.push('  - leave:', '  - wait: {inWorld: false, screen: TitleScreen, timeout: 90}', '  - reopen:', '  - wait: {inWorld: true, screen: null, timeout: 180}');
  cmd('item replace entity @s weapon.mainhand from entity @s hotbar.8');
  use(5);
  check(5);
  cmd('data get block 1 -60 0 Album[0].Name', 'outputContains: edited independently');
  cmd('execute if data block 5 -60 0 Album[63]');
  cmd('execute unless data block 5 -60 0 Album[64]');
  cmd('setblock 8 -60 0 xiaojingyu:photo_album_table');
  cmd('tp @s 8.5 -60 3.5 180 20');
  L.push('  - pick: {pos: [8, -60, 0], includeData: true, hasReference: false, hasAlbum: false, maxBytes: 1024}');
  use(9);
  cmd('data get block 9 -60 0 Album', 'success: false');
  cmd(`item replace entity @s weapon.mainhand with xiaojingyu:photo_album_table[xiaojingyu:album_reference="${'0'.repeat(64)}"]`);
  cmd('gamemode survival');
  use(11, false, ', actionBarContains: This world cannot find this album');
  cmd('execute if block 11 -60 0 minecraft:air');
  cmd('execute if items entity @s weapon.mainhand xiaojingyu:photo_album_table[xiaojingyu:album_reference]');
  L.push('  - leave:', '  - wait: {inWorld: false, screen: TitleScreen, timeout: 90}');
  return L.join('\n') + '\n';
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = cardText();
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(CARD_FILE, 'utf8') !== text) throw new Error('P5-006 is stale');
  } else fs.writeFileSync(CARD_FILE, text);
}
